"""Build input contracts: one Python manifest and deterministic frontend installs."""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def test_obsolete_duplicate_packaging_manifest_is_not_used():
    # The installer installs '.[desktop,dev]' from pyproject.toml, not a
    # divergent packaging/requirements.txt that misses active dependencies.
    assert (ROOT / "pyproject.toml").is_file()
    pyproject = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    assert '"pyinstaller>=6,<7"' in pyproject
    assert not (ROOT / "packaging/requirements.txt").exists()
    script = (ROOT / "scripts/build-windows.ps1").read_text(encoding="utf-8")
    assert "pip install -e '.[desktop,dev]'" in script
    assert "pip install -r" not in script


def test_frontend_lockfile_is_aligned_with_manifest_and_all_build_gates():
    package = json.loads((ROOT / "frontend/package.json").read_text(encoding="utf-8"))
    lock = json.loads((ROOT / "frontend/package-lock.json").read_text(encoding="utf-8"))
    assert lock["lockfileVersion"] >= 2
    assert package["version"] == lock["version"] == lock["packages"][""]["version"]
    assert package["dependencies"] == lock["packages"][""]["dependencies"]
    assert package["devDependencies"] == lock["packages"][""]["devDependencies"]

    windows = (ROOT / "scripts/build-windows.ps1").read_text(encoding="utf-8")
    validation = (ROOT / ".github/workflows/test.yml").read_text(encoding="utf-8")
    release = (ROOT / ".github/workflows/build-windows.yml").read_text(encoding="utf-8")
    assert "npm ci --prefix frontend --no-audit --no-fund" in windows
    assert "npm ci --no-audit --no-fund" in validation
    assert "npm ci --prefix frontend --no-audit --no-fund" in release

def test_playwright_browser_cache_tracks_the_pinned_smoke_dependency():
    workflow = (ROOT / ".github/workflows/test.yml").read_text(encoding="utf-8")
    assert "playwright@1.62.1" in workflow
    assert "key: studyflow-playwright-chromium-${{ runner.os }}-1.62.1" in workflow
    assert "path: ~/.cache/ms-playwright" in workflow
    assert "playwright\" install --with-deps chromium" in workflow


def test_root_tauri_cli_is_locked_for_windows_and_other_supported_hosts():
    manifest = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((ROOT / "package-lock.json").read_text(encoding="utf-8"))
    assert lock["lockfileVersion"] == 3
    assert manifest["name"] == lock["name"] == lock["packages"][""]["name"]
    assert manifest["version"] == lock["version"] == lock["packages"][""]["version"]
    assert manifest["devDependencies"] == lock["packages"][""]["devDependencies"]
    tauri_cli = lock["packages"].get("node_modules/@tauri-apps/cli")
    assert isinstance(tauri_cli, dict) and tauri_cli.get("version")
    assert lock["packages"].get("node_modules/@tauri-apps/cli-win32-x64-msvc", {}).get("integrity")

    windows = (ROOT / "scripts/build-windows.ps1").read_text(encoding="utf-8")
    assert "npm ci --no-audit --no-fund" in windows
    assert "npm install --no-audit --no-fund" not in windows


def test_rust_desktop_dependency_tree_is_committed_and_enforced():
    cargo = (ROOT / "src-tauri/Cargo.lock").read_text(encoding="utf-8")
    manifest = (ROOT / "src-tauri/Cargo.toml").read_text(encoding="utf-8")
    assert cargo.startswith("# This file is automatically @generated by Cargo.")
    assert 'name = "studyflow"' in cargo
    assert 'name = "tauri"' in cargo
    assert cargo.count("[[package]]") >= 100
    assert "[dependencies]" in manifest

    windows = (ROOT / "scripts/build-windows.ps1").read_text(encoding="utf-8")
    assert "cargo test --locked --manifest-path src-tauri/Cargo.toml" in windows


def test_one_time_lockfile_resolution_is_not_a_permanent_ci_job():
    workflow = (ROOT / ".github/workflows/test.yml").read_text(encoding="utf-8")
    assert "dependency-lock-review" not in workflow
    assert "STUDYFLOW_LOCK_DATA" not in workflow



def test_windows_build_compiles_frontend_once_via_tauri_before_build():
    windows = (ROOT / "scripts/build-windows.ps1").read_text(encoding="utf-8")
    tauri = json.loads((ROOT / "src-tauri/tauri.conf.json").read_text(encoding="utf-8"))
    assert tauri["build"]["beforeBuildCommand"] == "npm --prefix frontend run build"
    assert "npm run tauri -- build" in windows
    assert "npm --prefix frontend run build" not in windows
    # The React build is still required; removing the duplicate script call
    # must never disable the Tauri packaging hook.
    assert "npm ci --prefix frontend --no-audit --no-fund" in windows
