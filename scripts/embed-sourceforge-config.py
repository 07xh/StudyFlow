"""Embed a build-approved SourceForge open-source distribution project slug."""
from __future__ import annotations

import json
import os
from pathlib import Path
import re

project = os.getenv("STUDYFLOW_SOURCEFORGE_PROJECT", "").strip()
if project and not re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?", project):
    raise SystemExit("Invalid SourceForge project slug")
path = Path(__file__).resolve().parents[1] / "src/studyflow/services/_sourceforge_config.py"
path.write_text("# Generated by Windows package build; do not commit.\n" +
                "SOURCEFORGE_PROJECT = " + json.dumps(project) + "\n", encoding="utf-8")
print("SourceForge configured" if project else "SourceForge disabled; GitHub-only updates")
